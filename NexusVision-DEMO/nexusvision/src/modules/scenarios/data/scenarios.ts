const detection = (
  id: string,
  classId: string,
  label: string,
  confidence: number,
  x: number,
  y: number,
  width: number,
  height: number,
): Detection => ({ id, classId, label, confidence, box: { x, y, width, height } });
const mask = (
  id: string,
  classId: string,
  label: string,
  points: [number, number][],
  confidence = 0.94,
): SegmentationMask => ({
  id,
  classId,
  label,
  confidence,
  points,
  areaRatio:
    Math.abs(
      points.reduce((n, p, i) => {
        const q = points[(i + 1) % points.length];
        return n + p[0] * q[1] - q[0] * p[1];
      }, 0),
    ) / 2,
});
